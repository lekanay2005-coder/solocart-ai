/**
 * Regenerates tests/fixtures/offline-vectors.json — the shared test-vector
 * file both sides verify: server (tests/offline-vectors.test.mjs) and the
 * mobile app (apps/morrow-mobile/src/lib/vectors.test.ts).
 *
 * Values are fixed literals and signing is deterministic (Ed25519), so
 * re-running this must produce byte-identical output. Test-only keys.
 *
 *   node scripts/gen-offline-vectors.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ed25519 } from '@noble/curves/ed25519.js';
import { sha256 } from '@noble/hashes/sha2.js';
import { bytesToHex, utf8ToBytes } from '@noble/hashes/utils.js';
import {
  allowanceFields,
  authFields,
  b64FromBytes,
  confirmationFields,
  digest,
  serializeConfirmation,
  serializeRequest,
  signCanonical,
} from '../server/offline/protocol.mjs';

const seed = sha256(utf8ToBytes('solocart-morrow-shared-vectors-v1'));
const privateKey = new Uint8Array(seed);
const publicKey = ed25519.getPublicKey(privateKey);
const pubB64 = b64FromBytes(publicKey);

const EXPIRES = 4102444800000; // 2100-01-01 UTC — beyond every test runner's clock

const request = {
  version: 1,
  type: 'payment.request',
  id: 'req_00112233445566778899',
  merchant: {
    id: 'mer_morrow_demo',
    name: 'North & Pine',
    account: '•••• 2048', // non-ASCII on purpose: both sides' base64 must agree
    bmoniUserId: 'usr_vector_1',
  },
  amountMinor: 250000,
  currency: 'NGN',
  note: 'Invoice 1 — shared vector',
  nonce: 'n_aabbccddeeff00112233',
  createdAt: 1760000000000,
  expiresAt: EXPIRES,
};
request.checksum = digest(JSON.stringify(request));

const allowance = {
  version: 1,
  allowanceId: 'rsv_vector_0001',
  currency: 'NGN',
  valueMinor: 2000000,
  issuerPublicKey: pubB64,
  expiresAt: EXPIRES,
  createdAt: 1760000000000,
};
allowance.issuerSignature = signCanonical(privateKey, allowanceFields(allowance));

const authorization = {
  version: 1,
  type: 'reserve.authorization',
  allowanceId: allowance.allowanceId,
  sequence: 1,
  recipientRequestId: request.id,
  recipientName: request.merchant.name,
  amountMinor: 250000,
  currency: 'NGN',
  remainingMinor: 1750000,
  previousStateHash: bytesToHex(sha256(utf8ToBytes('genesis'))),
  nonce: 'n_99887766554433221100',
  timestamp: 1760000000500,
  issuerPublicKey: pubB64,
};
authorization.signature = signCanonical(privateKey, authFields(authorization));

const confirmation = {
  version: 1,
  type: 'payment.confirmation',
  requestId: request.id,
  amountMinor: 250000,
  currency: 'NGN',
  payerLabel: 'Vector payer',
  settlementReference: `${authorization.allowanceId}:${authorization.sequence}`,
  confirmedAt: 1760000000750,
  nonce: 'n_554433221100ffeedd',
  signerPublicKey: pubB64,
  offlineAuthorization: authorization,
};
confirmation.signature = signCanonical(privateKey, confirmationFields(confirmation));

const vectors = {
  note:
    'Shared offline-payments test vectors for the Morrow/SoloCart wire format, generated by scripts/gen-offline-vectors.mjs. '
    + 'Verified by tests/offline-vectors.test.mjs (server) and apps/morrow-mobile/src/lib/vectors.test.ts (mobile). '
    + 'Test-only keys — never used for a real payment.',
  deviceKeys: {
    seed: bytesToHex(seed),
    publicKey: pubB64,
  },
  request,
  requestPayload: serializeRequest(request),
  allowance,
  authorization,
  confirmation,
  confirmationPayload: serializeConfirmation(confirmation),
};

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'tests', 'fixtures', 'offline-vectors.json');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify(vectors, null, 2)}\n`);
console.log(`wrote ${out}`);
